/**
 * Generates Dart models for the Flutter app from generated/models.schema.json,
 * and copies the defaults templates into the app's assets.
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, '../generated/models.schema.json');
const appModels = resolve(here, '../../../app/lib/models/generated');
const appAssets = resolve(here, '../../../app/assets/schema');
mkdirSync(appModels, { recursive: true });
mkdirSync(appAssets, { recursive: true });

const out = resolve(appModels, 'models.dart');
execFileSync(
  'pnpm',
  [
    'exec',
    'quicktype',
    '--src-lang',
    'schema',
    '--lang',
    'dart',
    '--top-level',
    'PortfolioBuilderModels',
    '--copy-with',
    '--out',
    out,
    schemaPath,
  ],
  { cwd: resolve(here, '..'), stdio: 'inherit' },
);

const header =
  '// GENERATED by packages/schema (pnpm codegen). Do not edit by hand.\n' +
  '// ignore_for_file: type=lint\n';
writeFileSync(out, header + readFileSync(out, 'utf8'));
copyFileSync(resolve(here, '../generated/templates.json'), resolve(appAssets, 'templates.json'));
console.log('wrote', out);
